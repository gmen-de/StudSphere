/**
 * Turns a level of getSetThemeChildren() output into nav-dropdown item
 * shape, recursing into owned subthemes so a "Meine Sets"/"Meine
 * Minifiguren"-style menu can flyout into them (e.g. Train -> 9V) instead of
 * only showing the top level. $baseHref is the page's own theme-drilldown
 * link prefix (e.g. "?page=my_sets_themes&theme="), just missing the
 * trailing theme_id — shared by both menus since they're structurally
 * identical, just built from a different tree.
 *
 * @param array<int, array{theme_id:int, name:string, recursive_count:int}> $themeNodes
 * @return array<int, array{label:string, href:string, children?:array}>
 */
function buildOwnedThemeNavItems(array $tree, array $themeNodes, string $baseHref): array
{
    $items = [];
    foreach ($themeNodes as $theme) {
        $item = [
            'label' => $theme['name'],
            'href' => $baseHref . $theme['theme_id'],
        ];
        $subThemes = getSetThemeChildren($tree, $theme['theme_id']);
        if (!empty($subThemes)) {
            $item['children'] = buildOwnedThemeNavItems($tree, $subThemes, $baseHref);
        }
        $items[] = $item;
    }
    return $items;
}

/**
 * Renders one level of nav-dropdown items, recursing into a ".nav-subdropdown"
 * flyout for any item that carries its own 'children' (see
 * buildOwnedThemeNavItems()). Items may use either 'label' (already a
 * display string, e.g. a theme name) or 'labelKey' (translated). An item
 * shaped as ['divider' => true] (see getNavMenu()'s "Meine Minifiguren"
 * entry) renders as a plain separator instead of a link — generic, not
 * specific to any one dropdown, so any future static-entry-above-a-dynamic-
 * list case can reuse it the same way.
 *
 * @param array<int, array{label?:string, labelKey?:string, href?:string, children?:array, divider?:bool}> $items
 */
function renderNavDropdownItems(array $items): string
{
    $html = '';
    foreach ($items as $item) {
        if (!empty($item['divider'])) {
            $html .= '<hr class="nav-dropdown-divider">';
            continue;
        }
        $label = $item['label'] ?? t($item['labelKey']);
        $href = htmlspecialchars($item['href']);
        if (!empty($item['children'])) {
            $html .= '<div class="nav-dropdown-item">';
            $html .= '<a href="' . $href . '">' . htmlspecialchars($label) . '</a>';
            $html .= '<div class="nav-subdropdown">' . renderNavDropdownItems($item['children']) . '</div>';
            $html .= '</div>';
        } else {
            $html .= '<a href="' . $href . '">' . htmlspecialchars($label) . '</a>';
        }
    }
    return $html;
}

